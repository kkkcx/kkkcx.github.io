export function localDate(text){if(language==='en')return text;return text.replace(/([A-Z][a-z]+) (\d{4})/g,(_,month,year)=>`${year}年${monthNumbers[month]}月`).replace(/(\d{4})\.(\d{2})/g,(_,year,month)=>`${year}年${Number(month)}月`).replace('Now',t('education.present')).replace('Present',t('education.present'));}
