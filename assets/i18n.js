const STORAGE_KEY='caixin-language';
function initialLanguage(){const query=new URLSearchParams(location.search).get('lang');if(LANGUAGES.includes(query))return query;try{const saved=localStorage.getItem(STORAGE_KEY);if(LANGUAGES.includes(saved))return saved;}catch{}return 'en';}
let language=initialLanguage();
export const getLanguage=()=>language;
export function t(key,values={}){const entry=MESSAGES[key];if(!entry)throw new Error('Missing translation: '+key);return entry[LANGUAGES.indexOf(language)].replace(/\{(\w+)\}/g,(_,name)=>String(values[name]??'{'+name+'}'));}
export function setLanguage(next){if(!LANGUAGES.includes(next)||next===language)return false;language=next;try{localStorage.setItem(STORAGE_KEY,next);}catch{}const url=new URL(location.href);url.searchParams.set('lang',next);history.replaceState(history.state,'',url);window.dispatchEvent(new CustomEvent('language-change',{detail:next}));return true;}
